#!/usr/bin/env bash
# agent-memory-bridge.sh — one memory, read by Claude Code and Cursor.
#
#   AGENTS.md                        canonical, committed, hand-edited
#   CLAUDE.md            -> symlink  Claude Code reads CLAUDE.md and only CLAUDE.md
#   .cursor/rules/00-agent-memory.mdc  generated, alwaysApply, points at AGENTS.md
#
# .cursor/ is gitignored in this repo, so the Cursor-side rule is generated rather
# than committed. Run `init` after cloning.
#
#   ./scripts/agent-memory-bridge.sh init     create the links (idempotent)
#   ./scripts/agent-memory-bridge.sh check    verify; non-zero exit on drift (CI)
#   ./scripts/agent-memory-bridge.sh status   show what is wired up

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CANON="$ROOT/AGENTS.md"
CLAUDE="$ROOT/CLAUDE.md"
CURSOR_DIR="$ROOT/.cursor/rules"
CURSOR_RULE="$CURSOR_DIR/00-agent-memory.mdc"

red()  { printf '\033[31m%s\033[0m\n' "$*"; }
grn()  { printf '\033[32m%s\033[0m\n' "$*"; }
ylw()  { printf '\033[33m%s\033[0m\n' "$*"; }

write_cursor_rule() {
  mkdir -p "$CURSOR_DIR"
  cat > "$CURSOR_RULE" <<'EOF'
---
description: Shared agent memory. Canonical source is AGENTS.md at the repo root; CLAUDE.md is a symlink to it.
globs: ""
alwaysApply: true
---

# Shared agent memory

**Read `AGENTS.md` at the repository root before doing anything else in this repo.**
It holds the project invariants, the working agreements, the current state, and the
open decisions you must not silently resolve.

`CLAUDE.md` is a symlink to `AGENTS.md`. They are the same file. Claude Code and
Cursor share this memory — anything you record there, the other tool sees.

## When you learn something durable

Append it to the decision log at the bottom of `AGENTS.md`, one or two lines,
tagged `[YYYY-MM-DD] [cursor]`, linking the doc that holds the detail.
Session-scoped notes go in `docs/07-review/` instead.

## Do not

- Edit `CLAUDE.md`. It is a symlink; edit `AGENTS.md`.
- Edit this file. It is generated by `scripts/agent-memory-bridge.sh`.
- Resolve anything listed under "Open decisions" in `AGENTS.md` by picking a side
  in code. Stop and surface it.
EOF
}

cmd_init() {
  [ -f "$CANON" ] || { red "missing $CANON — the canonical memory must exist first"; exit 1; }

  if [ -L "$CLAUDE" ]; then
    ln -sfn "AGENTS.md" "$CLAUDE"
    grn "ok   CLAUDE.md -> AGENTS.md (refreshed)"
  elif [ -e "$CLAUDE" ]; then
    ylw "warn CLAUDE.md exists as a real file."
    ylw "     Merge its content into AGENTS.md, then:  rm CLAUDE.md && $0 init"
    exit 1
  else
    ln -s "AGENTS.md" "$CLAUDE"
    grn "ok   CLAUDE.md -> AGENTS.md (created)"
  fi

  write_cursor_rule
  grn "ok   .cursor/rules/00-agent-memory.mdc (generated)"
  grn "done"
}

cmd_check() {
  local fail=0

  [ -f "$CANON" ] || { red "FAIL AGENTS.md missing"; fail=1; }

  if [ ! -L "$CLAUDE" ]; then
    red "FAIL CLAUDE.md is not a symlink — Claude Code and Cursor have diverged"
    fail=1
  elif [ "$(readlink "$CLAUDE")" != "AGENTS.md" ]; then
    red "FAIL CLAUDE.md points at $(readlink "$CLAUDE"), expected AGENTS.md"
    fail=1
  else
    grn "ok   CLAUDE.md -> AGENTS.md"
  fi

  if [ ! -f "$CURSOR_RULE" ]; then
    ylw "warn Cursor rule missing — run: $0 init"
  else
    local tmp; tmp="$(mktemp)"
    cp "$CURSOR_RULE" "$tmp"
    write_cursor_rule
    if cmp -s "$tmp" "$CURSOR_RULE"; then
      grn "ok   Cursor rule current"
    else
      ylw "warn Cursor rule was stale and has been regenerated"
    fi
    rm -f "$tmp"
  fi

  # The memory earns its size back only if it stays small. Both tools load it every session.
  if [ -f "$CANON" ]; then
    local lines; lines=$(wc -l < "$CANON" | tr -d ' ')
    if [ "$lines" -gt 200 ]; then
      ylw "warn AGENTS.md is $lines lines. Over ~200, move detail into docs/ and link it."
    else
      grn "ok   AGENTS.md is $lines lines"
    fi
  fi

  [ "$fail" -eq 0 ] && grn "bridge intact" || red "bridge broken"
  return "$fail"
}

cmd_status() {
  printf 'canonical  %s\n' "$CANON"
  printf 'claude     %s%s\n' "$CLAUDE" "$([ -L "$CLAUDE" ] && printf ' -> %s' "$(readlink "$CLAUDE")")"
  printf 'cursor     %s%s\n' "$CURSOR_RULE" "$([ -f "$CURSOR_RULE" ] || printf ' (missing)')"
}

case "${1:-check}" in
  init)   cmd_init ;;
  check)  cmd_check ;;
  status) cmd_status ;;
  *) echo "usage: $0 {init|check|status}" >&2; exit 2 ;;
esac
